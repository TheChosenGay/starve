// Package primitive 定义碰撞库的图元：向量与各种形状。
//
// 这里只放「数据 + 它自己的方法」：
//   - 向量运算（加/减/点积/叉积/长度/归一化……）；
//   - 包围盒运算（并、外扩、平移、扫掠盒、包含判定）；
//   - 每种图元的紧包围盒 Bounds()（宽阶段的原料）；
//   - 类型标识 Kind()，以及 Shape / Solid 两个接口。
//
// 所有「需要同时看两个图元」的算法——最近点、相交、接触、扫掠、射线、圆弧与扇形、
// 按类型双分发——都在上一层 starve/pkg/collide 里。这样图元包可以独立演进，
// 也保证它不依赖任何算法实现。
//
// 图元都是值类型：可直接比较、可直接放进切片，没有指针字段、没有接口字段。
// 宽阶段索引里存的是它们的紧包围盒（再外扩成 fat AABB），不是它们本身。
